export const founderTree = StandardMerkleTree.of(
  founders.map((a) => [a.toLowerCase()]),
  ["address"],
);
export function founderProof(address: Address): Hex[] | undefined {
  for (const [i, [a]] of founderTree.entries())
    if (a === address.toLowerCase()) return founderTree.getProof(i) as Hex[];
}
